/** Problems of one song (empty = OK). song = { slot, title_hi, title_roman, deity, mood, festival, lyrics, public_domain_text } */
export function checkSong(song, { plan = null, others = [], rules = RULES } = {}) {
  const e = [];
  const lyr = String(song.lyrics || '');
  if (/[‌‍]/.test(lyr)) e.push('lyrics: write plain Devanagari (the spelling rules add the ZWJ for singing)');
  const tags = lyr.match(/\[[^\]]*\]/g) || [];
  if (!/^\s*\[chorus\]/i.test(lyr)) e.push('lyrics: start with [chorus] (chorus first)');
  if (tags.some((t) => !/^\[(chorus|verse|bridge)\]$/i.test(t))) e.push('lyrics: only [chorus] / [verse] / [bridge] tags');
  if (tags.filter((t) => /chorus/i.test(t)).length < 2) e.push('lyrics: the chorus comes back at least once ([chorus] twice)');
  const lines = sungLines(lyr);
  // full-length songs (song.full, 13 Nov 2026 Chhath jukebox: 2-3 min, verse-chorus-verse-chorus) may have up to 24 lines
  const maxLines = song.full ? 24 : 16;
  if (lines.length < 6 || lines.length > maxLines) e.push(`lyrics: 6-${maxLines} sung lines (has ${lines.length})`);
  for (const l of lines) if ([...l].length < 6 || [...l].length > 48) e.push(`line "${l}": 6-48 characters`);
  const words = lyr.replace(/\[[^\]]*\]/g, ' ');
  for (const f of rules.forbidden) if (new RegExp(f.re, 'u').test(words)) e.push(`lyrics: ${f.why}`);
  if (song.deity === 'khatu') for (const f of rules.forbidden_khatu) if (new RegExp(f.re, 'u').test(words)) e.push(`lyrics: ${f.why}`);
  if (/सती|sati/i.test(`${song.title_hi || ''} ${song.title_roman || ''} ${song.festival || ''}`)) e.push('no Rani Sati bhajans');
  if (!rules.primary[song.deity]) e.push(`deity "${song.deity}" unknown (${Object.keys(rules.primary).join(' / ')})`);
  else {
    const chorus = (lyr.match(/\[chorus\]([\s\S]*?)(?=\[|$)/i) || [, ''])[1];
    const occ = nameOccurrences(chorus, rules).filter((o) => !o.sri && o.deity === song.deity);
    if (!occ.length) e.push(`chorus: name ${rules.primary[song.deity].join(' / ')} at least once NOT right after "श्री" (e.g. "खाटू वाले श्याम")`);
  }
  if (!['thaath', 'bhaavuk'].includes(song.mood)) e.push('mood: thaath | bhaavuk');
  if (!/^[\x20-\x7e]{3,60}$/.test(song.title_roman || '')) e.push('title_roman: 3-60 plain ASCII characters');
  if (!/[ऀ-ॿ]/.test(song.title_hi || '')) e.push('title_hi: Devanagari title');
  if (!song.public_domain_text) {
    for (const l of lines) {
      const k = rules.known_lines.find((x) => dice(x, l) >= 0.7 || norm(l).includes(norm(x)));
      if (k) e.push(`line "${l}" is too close to an existing bhajan ("${k}"): write your own`);
    }
  }
  const first = lines[0] || '';
  const dup = others.find((o) => o && dice(o, first) >= 0.8);
  if (dup) e.push(`chorus line 1 "${first}" repeats "${dup}" (library or this batch): write a new one`);
  if (plan) {
    if (song.deity !== plan.deity) e.push(`deity must be ${plan.deity} (plan slot ${plan.slot})`);
    if (song.mood !== plan.mood) e.push(`mood must be ${plan.mood} (plan slot ${plan.slot})`);
    if ((song.festival || null) !== (plan.festival || null)) e.push(`festival must be ${plan.festival || 'null'} (plan slot ${plan.slot})`);
  }
  return [...new Set(e)];
}

/** All songs: { ok: [song], bad: [{slot, problems}] }. */
export function checkLyrics(doc, plan = null, libraryFirstLines = []) {
  const ok = [], bad = [];
  const seen = [...libraryFirstLines];
  for (const s of doc.songs || []) {
    const p = plan?.songs?.find((x) => x.slot === s.slot) || null;
    const problems = plan && !p ? [`slot ${s.slot} is not in the plan`] : checkSong(s, { plan: p, others: seen });
    if (problems.length) bad.push({ slot: s.slot, problems });
    else { ok.push(s); seen.push(sungLines(s.lyrics)[0]); }
  }
  return { ok, bad };
}

