// ---------------------------------------------------------------- text helpers
const ZW = /[‌‍]/g;
export const plain = (s) => String(s || '').normalize('NFC').replace(ZW, '');
/** Letters only (Devanagari + word chars), no section tags / spaces / punctuation / nukta / ZWJ: the CER + alignment form. */
export const norm = (s) => plain(s).replace(/\[[^\]]*\]/g, ' ').replace(/़/g, '').replace(/[^\p{L}\p{M}\p{N}]+/gu, '');
const sungLines = (lyrics) => plain(lyrics).split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !/^\[.*\]$/.test(l));

/** The lyrics ACE-Step reads: spelling.json `sing` rules on plain Devanagari (श्याम -> श्‍याम), every other word plain. */
export function singLyrics(lyrics, rules = RULES) {
  let s = plain(lyrics);
  for (const r of rules.sing) s = s.split(r.word).join(r.sing);
  return s;
}

export function editDistance(a, b) {
  const A = [...a], B = [...b];
  let prev = Array.from({ length: B.length + 1 }, (_, j) => j);
  for (let i = 1; i <= A.length; i++) {
    const cur = [i];
    for (let j = 1; j <= B.length; j++) cur.push(Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (A[i - 1] !== B[j - 1])));
    prev = cur;
  }
  return prev[B.length];
}
export function cer(ref, hyp) {
  const a = norm(ref), b = norm(hyp);
  return a ? Math.round((editDistance(a, b) / [...a].length) * 1000) / 1000 : null;
}
const bigrams = (s) => { const c = [...norm(s)]; const out = new Set(); for (let i = 0; i < c.length - 1; i++) out.add(c[i] + c[i + 1]); return out; };
export function dice(a, b) {
  const A = bigrams(a), B = bigrams(b);
  if (!A.size || !B.size) return 0;
  let n = 0;
  for (const x of A) if (B.has(x)) n++;
  return (2 * n) / (A.size + B.size);
}

// ---------------------------------------------------------------- deity names: where they are, what was heard there
/**
 * Every deity-name occurrence in the written lyrics: { word, deity, at (index into norm(lyrics) chars), len, sri }.
 * sri = right after श्री (also written together as श्रीश्याम): not checked.
 */
export function nameOccurrences(lyrics, rules = RULES) {
  const words = plain(lyrics).replace(/\[[^\]]*\]/g, ' ').split(/[^\p{L}\p{M}\p{N}]+/u).filter(Boolean);
  const names = Object.keys(rules.names).sort((a, b) => b.length - a.length);
  const out = [];
  let at = 0;
  words.forEach((w0, k) => {
    const w = norm(w0);
    const taken = [];
    for (const n of names) {
      let i = w.indexOf(n);
      while (i >= 0) {
        if (!taken.some(([a, b]) => i < b && a < i + n.length)) {
          taken.push([i, i + n.length]);
          const prefix = w.slice(0, i);
          const sri = /श्रि?ी?$/.test(prefix) || (i === 0 && /^श्रि?ी?$/.test(norm(words[k - 1] || '')));
          out.push({ word: n, deity: rules.names[n].deity, at: [...w.slice(0, i)].length + at, len: [...n].length, sri });
        }
        i = w.indexOf(n, i + 1);
      }
    }
    at += [...w].length;
  });
  return out.sort((a, b) => a.at - b.at);
}

/** Character alignment of hyp to ref (Levenshtein backtrace): for each ref char, the hyp index it lines up with or -1. */
export function align(ref, hyp) {
  const A = [...ref], B = [...hyp];
  const n = A.length, m = B.length, W = m + 1;
  const D = new Int32Array((n + 1) * W);
  for (let j = 0; j <= m; j++) D[j] = j;
  for (let i = 1; i <= n; i++) {
    D[i * W] = i;
    for (let j = 1; j <= m; j++) D[i * W + j] = Math.min(D[(i - 1) * W + j] + 1, D[i * W + j - 1] + 1, D[(i - 1) * W + j - 1] + (A[i - 1] !== B[j - 1]));
  }
  const map = new Array(n).fill(-1);
  let i = n, j = m;
  while (i > 0 || j > 0) {
    if (i > 0 && j > 0 && D[i * W + j] === D[(i - 1) * W + j - 1] + (A[i - 1] !== B[j - 1])) { map[i - 1] = j - 1; i--; j--; }
    else if (i > 0 && D[i * W + j] === D[(i - 1) * W + j] + 1) i--;
    else j--;
  }
  return map;
}

/**
 * Deity-name check of one take: { ok, checked, right, wrong: [{word, heard}], missingTail, own } where own = right
 * positions of the song's deity. ok = no wrong position and at least one right position of `deity`.
 */
export function nameCheck(lyrics, whisper, deity, rules = RULES) {
  const ref = norm(lyrics), hyp = norm(whisper);
  const H = [...hyp];
  const map = align(ref, hyp);
  const lastHeard = Math.max(-1, ...map);
  const lastRef = map.findLastIndex((x) => x >= 0);
  const res = { checked: 0, right: 0, wrong: [], missingTail: 0, own: 0 };
  for (const o of nameOccurrences(lyrics, rules)) {
    // Only the song's own deity: in a Khatu song "भोले भक्तों" means "innocent devotees", not Bhole Baba.
    if (o.sri || o.deity !== deity) continue;
    const js = map.slice(o.at, o.at + o.len).filter((x) => x >= 0);
    if (!js.length) {
      if (o.at > lastRef || lastHeard < 0) { res.missingTail++; continue; } // the song ended before this line
      res.checked++;
      res.wrong.push({ word: o.word, heard: '' });
      continue;
    }
    const heard = H.slice(Math.min(...js), Math.max(...js) + 1).join('');
    res.checked++;
    if (new RegExp(rules.names[o.word].ok, 'u').test(heard)) {
      res.right++;
      if (o.deity === deity) res.own++;
    } else res.wrong.push({ word: o.word, heard });
  }
  res.ok = !res.wrong.length && res.own > 0;
  return res;
}

/** Where the chorus starts in a take (s): the earliest Whisper segment that sounds like the chorus's first line. */
export function chorusAt(segments = [], lyrics = '') {
  const first = sungLines(lyrics)[0] || '';
  const segs = segments.filter((s) => s && typeof s.start === 'number' && norm(s.text));
  const hit = segs.find((s) => dice(first, s.text) >= 0.45 || (norm(s.text).length > 6 && norm(first).includes(norm(s.text))));
  const sung = segs.find((s) => (s.no_speech_prob ?? 0) < 0.6);
  const at = hit ? hit.start : sung ? sung.start : 0;
  return Math.round(at * 100) / 100;
}

