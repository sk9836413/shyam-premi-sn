const addDays = (iso, n) => new Date(Date.parse(`${iso}T00:00:00Z`) + n * 864e5).toISOString().slice(0, 10);

export function planWeek({ from, days = 7, count = 13, festivals = [], libraryFirstLines = [], libraryFestivals = {} }) {
  const to = addDays(from, days);
  // A festival the library already has >= 3 bhajans for is not planned again (13 Nov 2026: the Chhath batch
  // bhajan-chhath26 ran the evening before the first weekly batch; the weekly batch makes other deities instead).
  const fest = festivals.filter((f) => f.date >= from && f.date <= to && f.theme && ['big', 'status'].includes(f.tier) && !/sati/i.test(`${f.key} ${f.label}`))
    .filter((f) => (libraryFestivals[f.theme] || 0) < 3)
    .map((f) => ({ ...f, deity: FEST_DEITY[f.theme] || null })).filter((f) => f.deity);
  const byTheme = [...new Map(fest.map((f) => [f.theme, f])).values()].sort((a, b) => (a.tier === 'big' ? 0 : 1) - (b.tier === 'big' ? 0 : 1) || a.date.localeCompare(b.date));
  const songs = [];
  for (const f of byTheme) {
    if (songs.length >= 4) break;
    const name = f.names?.[0] || null;
    songs.push({ deity: f.deity, mood: 'thaath', festival: f.theme, festival_name: name, festival_date: f.date });
    if (f.tier === 'big' && songs.length < 4) songs.push({ deity: f.deity, mood: 'bhaavuk', festival: f.theme, festival_name: name, festival_date: f.date });
  }
  for (const [deity, mood] of BASE) {
    if (songs.length >= count) break;
    songs.push({ deity, mood, festival: null, ...(SUBJECT[deity] && !songs.some((x) => x.subject) ? { subject: SUBJECT[deity] } : {}) });
  }
  const { year, week } = isoWeek(from);
  const tag = `${year}w${String(week).padStart(2, '0')}`;
  return {
    batch: `bhajan-${tag}`, from, to, count: songs.length,
    songs: songs.map((s, k) => ({ slot: k + 1, ...s, deity_name: DEITY_NAMES[s.deity], bpm: s.mood === 'thaath' ? [124, 128, 132, 126, 130][k % 5] : [76, 80, 72, 84][k % 4] })),
    avoid_first_lines: libraryFirstLines,
  };
}

