// Original music batch on Kaggle's free GPU with ACE-Step 1.5 (kernel sps-music, music/kaggle/acestep_batch.py).
//   node music/gen.mjs push  --batch music/lyrics/<batch>.json [--kind vocal|instrumental] [--qa urls.json] [--code kaggle/<script>.py]
//        [--lock-minutes 60] [--needs-minutes 60] -> refuses inside (or, with --needs-minutes, running into) the no-extra-session windows
//        (09:00-11:30 and 18:30-21:00 IST), while another sps-* GPU kernel runs (animate/kaggle.mjs lock), or with under
//        --min-hours (default 8) of weekly GPU quota left; then pushes one private T4 session (stops itself after ~38 min)
//   node music/gen.mjs status
//   node music/gen.mjs wait [--minutes 55] [--queue-minutes 90] [--now] -> exit 0 once the session is COMPLETE, 1 ERROR /
//        cancelled, 2 still QUEUED after --queue-minutes or RUNNING for over --minutes (import later: mode=import)
//   node music/gen.mjs verify --batch <batch.json>                 -> exit 0 if the kernel's latest version runs this batch
//   node music/gen.mjs fetch --to <dir>                            -> results.json + <id>.mp3 (+ <id>.vocals.mp3)
//   node music/gen.mjs import --from <dir> --batch <batch.json> [--vocals]
//        -> tracks that pass QA (duration, loudness, true peak, clipping; vocals also Whisper CER) go to music/library/
//           as <id>.ogg + <id>.licence.json ("original, generated by ACE-Step 1.5 (MIT)"). Vocal bhajans are kept out
//           of the library unless --vocals (owner decision after the quality verdict).
// Login: the Kaggle CLI's own credentials (KAGGLE_CLI = path to the CLI if not on PATH).
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { normaliseLoudness, sha256, windowAhead } from './engine.mjs';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(DIR, '..');
const CLI = process.env.KAGGLE_CLI || 'kaggle';
const USER = process.env.KAGGLE_USER || 'sk9846413';
const KERNEL = `${USER}/sps-music`;
const args = process.argv.slice(2);
const cmd = args[0] || 'status';
const opt = (n, d) => (args.includes(n) ? args[args.indexOf(n) + 1] : d);
const kaggle = (...a) => { const r = spawnSync(CLI, a, { encoding: 'utf8' }); return { ok: r.status === 0, out: `${r.stdout || ''}${r.stderr || ''}` }; };

export function resolveJobs(batch) {
  const byId = Object.fromEntries(batch.jobs.map((j) => [j.id, j]));
  return batch.jobs.map((j) => {
    const job = { ...j };
    if (/^SAME_AS:/.test(job.lyrics || '')) job.lyrics = byId[job.lyrics.slice(8)].lyrics;
    if (job.lyrics_devanagari_of) job.lyrics_devanagari = byId[job.lyrics_devanagari_of].lyrics;
    if (job.kind === 'vocal' && job.singer && batch.singer?.[job.singer]) job.caption = `${job.caption}, ${batch.singer[job.singer]}`;
    return job;
  });
}

function push() {
  const batchFile = opt('--batch');
  if (!batchFile) throw new Error('--batch <file> needed');
  // --needs-minutes N: the whole session (lock wait excluded) must fit before the next blocked window.
  const needs = Number(opt('--needs-minutes', '0'));
  const blocked = windowAhead(new Date(), needs);
  if (blocked) { console.log(JSON.stringify({ push: 'refused', reason: `no extra Kaggle session ${blocked} IST` })); process.exit(3); }
  const env = { ...process.env, SPS_SLOT: 'music' };
  const lock = spawnSync('node', [path.join(ROOT, 'animate', 'kaggle.mjs'), 'lock', '--minutes', opt('--lock-minutes', '0')], { encoding: 'utf8', env });
  if (lock.status !== 0) { console.log(JSON.stringify({ push: 'refused', reason: 'another GPU kernel is running', lock: (lock.stdout || '').trim() })); process.exit(3); }
  const late = windowAhead(new Date(), needs); // the lock wait may have run into a window
  if (late) { console.log(JSON.stringify({ push: 'refused', reason: `after the lock wait: no extra Kaggle session ${late} IST` })); process.exit(3); }
  const q = spawnSync('node', [path.join(ROOT, 'animate', 'kaggle.mjs'), 'quota', '--min', opt('--min-hours', '8')], { encoding: 'utf8', env });
  if (q.status === 2) { console.log(JSON.stringify({ push: 'refused', reason: 'GPU quota', quota: (q.stdout || '').trim() })); process.exit(3); }
  const jobs = resolveJobs(JSON.parse(fs.readFileSync(batchFile, 'utf8'))).filter((j) => !opt('--kind') || j.kind === opt('--kind'));
  // --qa <file>: [{id, url, kind}] earlier tracks (public URLs) to re-check in the same session (CLAP / Whisper)
  const qa = opt('--qa') ? JSON.parse(fs.readFileSync(opt('--qa'), 'utf8')) : [];
  const dir = path.resolve(opt('--push-dir', path.join(os.tmpdir(), 'sps-music-push')));
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  // --code <file>: another kernel script with the same __JOBS__ slot (e.g. music/kaggle/pron_ab.py, the pronunciation A/B)
  const code = fs.readFileSync(opt('--code', path.join(DIR, 'kaggle', 'acestep_batch.py')), 'utf8').replace('__JOBS__', JSON.stringify(jobs).replace(/'''/g, ''))
    .replace('__QA__', JSON.stringify(qa).replace(/'''/g, ''));
  fs.writeFileSync(path.join(dir, 'acestep_batch.py'), code);
  fs.writeFileSync(path.join(dir, 'kernel-metadata.json'), JSON.stringify({
    id: KERNEL, title: 'sps-music', code_file: 'acestep_batch.py', language: 'python', kernel_type: 'script', is_private: true,
    enable_gpu: true, enable_internet: true, machine_shape: 'NvidiaTeslaT4', dataset_sources: [], competition_sources: [], kernel_sources: [],
  }, null, 2));
  const r = kaggle('kernels', 'push', '-p', dir);
  console.log(r.out.trim().split('\n').pop());
  process.exit(r.ok && /successfully pushed/i.test(r.out) ? 0 : 1);
}

// The CLI's status line ("sk9846413/sps-music has status \"KernelWorkerStatus.QUEUED\"", older CLIs: "queued") -> QUEUED,
// RUNNING, COMPLETE, ERROR, CANCEL_REQUESTED, CANCEL_ACKNOWLEDGED, NEW_SCRIPT; '' when the call failed (API hiccup).
export function kernelState(out) {
  return (String(out || '').match(/has status\s*"?(?:KernelWorkerStatus\.)?([A-Za-z_]+)"?/i)?.[1] || '').toUpperCase();
}

/**
 * One poll of `wait` (bhajan-2026w46, 14 Nov 2026: the session sat QUEUED past the old flat 75 min, the step failed and
 * the finished takes were never imported). The queue has its own budget (--queue-minutes); the run budget (--minutes)
 * counts from the first RUNNING. Empty / unknown states (API errors) keep the last known state.
 * Returns { state, verdict: 'wait' | 'complete' | 'failed' | 'queued-too-long' | 'run-too-long', runningSince }.
 */
export function waitStep({ seen, last = '', now, t0, runningSince = null, runMinutes, queueMinutes }) {
  const state = /^(QUEUED|RUNNING|COMPLETE|ERROR|CANCEL_?REQUESTED|CANCEL_?ACKNOWLEDGED|NEW_?SCRIPT)$/.test(seen || '') ? seen : last;
  if (state === 'RUNNING' && runningSince == null) runningSince = now;
  if (state === 'COMPLETE') return { state, verdict: 'complete', runningSince };
  if (/^(ERROR|CANCEL)/.test(state)) return { state, verdict: 'failed', runningSince };
  if (runningSince != null) return { state, verdict: now - runningSince > runMinutes * 60e3 ? 'run-too-long' : 'wait', runningSince };
  return { state, verdict: now - t0 > queueMinutes * 60e3 ? 'queued-too-long' : 'wait', runningSince };
}

// wait [--minutes 55] [--queue-minutes 90] [--now]: exit 0 COMPLETE, 1 ERROR / cancelled, 2 still queued / running at the
// end (the session usually finishes later: import it then with music-weekly.yml mode=import). --now polls at once (resume);
// right after a push the first poll waits a minute, so the previous version's COMPLETE is never read.
async function wait() {
  const t0 = Date.now();
  const runMinutes = Number(opt('--minutes', 55));
  const queueMinutes = Number(opt('--queue-minutes', 90));
  let s = { state: '', verdict: 'wait', runningSince: null };
  let first = true, errors = 0;
  for (;;) {
    if (!(first && args.includes('--now'))) await new Promise((r) => setTimeout(r, 60e3));
    first = false;
    const seen = kernelState(kaggle('kernels', 'status', KERNEL).out);
    if (!seen) errors += 1;
    const prev = s.state;
    s = waitStep({ seen, last: s.state, now: Date.now(), t0, runningSince: s.runningSince, runMinutes, queueMinutes });
    if (s.state !== prev) console.log(`${new Date().toISOString()} ${s.state || 'unknown'}`);
    if (s.verdict !== 'wait') break;
  }
  console.log(JSON.stringify({ status: s.state || 'unknown', verdict: s.verdict, minutes: Math.round((Date.now() - t0) / 6e4), api_errors: errors }));
  process.exit(s.verdict === 'complete' ? 0 : s.verdict === 'failed' ? 1 : 2);
}

/** The jobs embedded in a pushed kernel script (JOBS = json.loads(r'''...''')), or null. */
export function jobsInSource(src) {
  const m = String(src || '').match(/JOBS = json\.loads\(r'''([\s\S]*?)'''\)/);
  try { return m ? JSON.parse(m[1]) : null; } catch { return null; }
}

/** Does the kernel's current version run exactly this batch (same ids, seeds, lyrics, durations)? [] = yes, else reasons. */
export function sameBatch(kernelJobs, batch) {
  if (!kernelJobs) return ['no JOBS found in the kernel source'];
  const key = (j) => JSON.stringify([j.id, j.seeds, j.lyrics, j.duration]);
  const want = resolveJobs(batch).map(key), got = kernelJobs.map(key);
  const why = [];
  if (want.length !== got.length) why.push(`kernel has ${got.length} jobs, the batch ${want.length}`);
  const missing = want.filter((k) => !got.includes(k)).map((k) => JSON.parse(k)[0]);
  if (missing.length) why.push(`differs from the batch for: ${missing.join(', ')}`);
  return why;
}

// verify --batch <file>: the kernel's latest version is this batch (resume safety: never import another batch's takes).
function verify() {
  const batch = JSON.parse(fs.readFileSync(opt('--batch'), 'utf8'));
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sps-music-pull-'));
  const r = kaggle('kernels', 'pull', KERNEL, '-p', dir);
  const py = r.ok ? fs.readdirSync(dir).filter((f) => f.endsWith('.py')) : [];
  const jobs = py.map((f) => jobsInSource(fs.readFileSync(path.join(dir, f), 'utf8'))).find(Boolean) || null;
  fs.rmSync(dir, { recursive: true, force: true });
  const why = r.ok ? sameBatch(jobs, batch) : [`kernels pull failed: ${r.out.trim().split('\n').pop()}`];
  console.log(JSON.stringify({ kernel: KERNEL, batch: batch.batch, same: !why.length, why }));
  process.exit(why.length ? 4 : 0);
}

function fetchOut() {
  const to = path.resolve(opt('--to', path.join(os.tmpdir(), 'sps-music-out')));
  fs.mkdirSync(to, { recursive: true });
  const r = kaggle('kernels', 'output', KERNEL, '-p', to);
  console.log(r.out.trim().split('\n').slice(-3).join('\n'));
  process.exit(r.ok ? 0 : 1);
}

const INDIAN = ['solo bansuri flute', 'sitar', 'santoor', 'tabla drums', 'dhol drums', 'harmonium', 'shehnai', 'veena', 'temple bells'];
// Share of the CLAP zero-shot probability on Indian instruments (full distribution if present, else the top 4 = a lower bound).
export function indianShare(t) {
  const pairs = t.clap ? Object.entries(t.clap) : t.clap_top;
  if (!pairs) return null;
  return pairs.filter(([l]) => INDIAN.includes(l)).reduce((a, [, p]) => a + p, 0);
}

// QA gate for the library (same numbers the kernel measured).
export function passesQa(t, { vocals = false } = {}) {
  const why = [];
  if (t.error || !t.file) why.push(t.error || 'no file');
  if (!(t.seconds >= 25)) why.push(`too short (${t.seconds})`);
  if (t.true_peak != null && t.true_peak > 0.5) why.push(`true peak ${t.true_peak}`);
  if (t.clip_share != null && t.clip_share > 0.001) why.push(`clipping ${(t.clip_share * 100).toFixed(2)}%`);
  if (t.lufs != null && (t.lufs < -35 || t.lufs > -5)) why.push(`loudness ${t.lufs}`);
  if (t.kind !== 'vocal' && ((t.clap_singing ?? 0) > 0.5 || (t.whisper_words ?? 0) > 12)) why.push(`singing heard in an instrumental (CLAP ${t.clap_singing}, ${t.whisper_words} words)`);
  // CLAP must hear Indian instruments (batch-001: santoor/sarangi/aarti prompts came out "western rock" / "EDM" to CLAP).
  const share = indianShare(t);
  if (t.kind !== 'vocal' && share != null && share < 0.15) why.push(`CLAP hears few Indian instruments (${share.toFixed(2)})`);
  if (t.kind === 'vocal') {
    if (!vocals) why.push('vocal bhajans not enabled for the library');
    if (!(t.cer != null && t.cer <= 0.35)) why.push(`Whisper CER ${t.cer}`);
  }
  return why;
}

function importBatch() {
  const from = path.resolve(opt('--from'));
  const res = JSON.parse(fs.readFileSync(path.join(from, 'results.json'), 'utf8'));
  const batch = JSON.parse(fs.readFileSync(opt('--batch'), 'utf8'));
  const meta = Object.fromEntries(batch.jobs.map((j) => [j.id, j]));
  const lib = path.join(DIR, 'library');
  const today = new Date().toISOString().slice(0, 10);
  const report = [];
  for (const t of res.tracks) {
    const why = passesQa(t, { vocals: args.includes('--vocals') });
    report.push({ id: t.id, ok: !why.length, why });
    if (why.length) continue;
    const id = `gen-${t.id}`;
    const src = [path.join(from, t.file), path.join(from, 'out', t.file)].find((f) => fs.existsSync(f));
    normaliseLoudness(src, path.join(lib, `${id}.ogg`));
    const j = meta[t.id] || {};
    fs.writeFileSync(path.join(lib, `${id}.licence.json`), `${JSON.stringify({
      id, title: t.id, moods: [j.mood || t.mood || 'calm'], kind: t.kind, bpm: t.bpm, deity: j.deity || null,
      source: 'original', licence: `original, generated by ACE-Step 1.5 (MIT; ${res.licence === 'MIT' ? 'commercial use of outputs allowed per the model card' : res.licence})`,
      licence_url: 'https://huggingface.co/ACE-Step/Ace-Step1.5', model: res.model, model_licence: 'MIT',
      generated: { batch: batch.batch, seed: t.seed, caption: t.caption, lyrics: t.kind === 'vocal' ? t.lyrics : '[Instrumental]',
        public_domain_text: j.public_domain_text || null, kaggle_kernel: KERNEL },
      qa: { seconds: t.seconds, lufs: t.lufs, true_peak: t.true_peak, clip_share: t.clip_share, cer: t.cer ?? null },
      attribution: null, redistributable: true, content_id: 'not registered (our own generation)', checked: today,
      sha256: sha256(path.join(lib, `${id}.ogg`)),
    }, null, 2)}\n`);
  }
  console.log(JSON.stringify(report, null, 1));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (cmd === 'push') push();
  else if (cmd === 'wait') await wait();
  else if (cmd === 'verify') verify();
  else if (cmd === 'fetch') fetchOut();
  else if (cmd === 'import') importBatch();
  else console.log(kaggle('kernels', 'status', KERNEL).out.trim());
}
