// Shyam Premi SN music engine (Nov 2026): real music under every Short instead of the synthesized tanpura drone.
// Off unless the repo variable MUSIC_ENGINE=on (daily.yml passes it as env); then story/render-story.mjs asks musicFor()
// for one track from music/library/ and uses it in place of the drone, in the same bus that is sidechain-ducked under
// the voice and normalised to -14 LUFS at the end.
// Licence rule (owner, Nov 2026): NO copyrighted songs or bhajan recordings, no label tracks, nothing ripped from
// YouTube/Instagram/JioSaavn even with credit, no owner/family voices. The library holds only
//   - CC0 / public-domain-dedicated recordings whose uploader is the performer (Freesound, Internet Archive), re-cut
//     and arranged here (music/build-library.mjs, sources in music/sources.json), and
//   - original music generated by ACE-Step 1.5 (MIT) on Kaggle (music/gen.mjs).
// Every library file <id>.ogg needs <id>.licence.json (validateLicence below; `node music/check-licences.mjs` fails
// the build otherwise) with the source URL, licence, date checked, attribution (null = none needed) and the file's sha256.
// Selection: mood from the spec (festival/status -> festive, darshan -> calm, katha -> emotional, aarti -> aarti;
// spec.music_mood overrides), never a track used in the 7 days before (story/published/*.json keep spec.music.id), the
// pick is stable for a slug. The chosen track is written into the spec as spec.music (id, mood, licence).
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = path.dirname(fileURLToPath(import.meta.url));
export const LIBRARY = path.join(DIR, 'library');
export const MOODS = ['calm', 'emotional', 'aarti', 'festive'];
// Licences the library accepts: no attribution duties, no share-alike, no non-commercial, no Content ID owners.
export const ALLOWED_LICENCES = [/^CC0 1\.0\b/, /^Public Domain Dedication\b/, /^original, generated by /, /^original arrangement of CC0\b/];
const NEIGHBOURS = { festive: ['aarti', 'calm'], aarti: ['festive', 'calm'], calm: ['emotional', 'aarti'], emotional: ['calm', 'aarti'] };
const REPEAT_DAYS = 7;

// No extra Kaggle session in these IST windows (the daily Shorts' GPU runs; coordinator rule).
export function istWindowBlocked(d) {
  const ist = new Date(d.getTime() + 330 * 60e3);
  const m = ist.getUTCHours() * 60 + ist.getUTCMinutes();
  if (m >= 9 * 60 && m < 11 * 60 + 30) return '09:00-11:30';
  if (m >= 18 * 60 + 30 && m < 21 * 60) return '18:30-21:00';
  return null;
}

// The blocked window a session starting at `d` and running `minutes` would touch (null = none): a batch must END before
// 09:00 / 18:30 IST too, not only start outside the windows.
export function windowAhead(d, minutes = 0) {
  for (let m = 0; m <= minutes; m += 5) {
    const w = istWindowBlocked(new Date(d.getTime() + m * 60e3));
    if (w) return w;
  }
  return null;
}

export const sha256 = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');

// Returns a list of problems (empty = valid). `audio` = path of the track's audio file (checked for the sha256).
export function validateLicence(j, audio) {
  const e = [];
  if (!j || typeof j !== 'object') return ['not a JSON object'];
  if (!/^[a-z0-9][a-z0-9-]{2,80}$/.test(j.id || '')) e.push('id missing or not kebab-case');
  if (!Array.isArray(j.moods) || !j.moods.length || j.moods.some((m) => !MOODS.includes(m))) e.push(`moods must be a non-empty subset of ${MOODS.join('/')}`);
  if (typeof j.licence !== 'string' || !ALLOWED_LICENCES.some((r) => r.test(j.licence))) e.push(`licence "${j.licence}" not allowed (CC0 / public-domain dedication / original only)`);
  if (!/^https:\/\//.test(j.licence_url || '')) e.push('licence_url missing');
  if (!/^\d{4}-\d{2}-\d{2}$/.test(j.checked || '')) e.push('checked (YYYY-MM-DD) missing');
  if (!('attribution' in j) || (j.attribution !== null && typeof j.attribution !== 'string')) e.push('attribution must be a string or null');
  if (j.redistributable !== true) e.push('redistributable must be true to keep the file in the repo');
  if (/\bBY[- ](NC|ND|SA)\b|non-?commercial|no ?deriv|share ?alike|\/by-(nc|nd|sa)\b/i.test(`${j.licence} ${j.licence_url}`)) e.push('NC/ND/SA terms are not allowed');
  const comps = j.source === 'original' ? [] : j.components;
  if (j.source !== 'original') {
    if (!Array.isArray(comps) || !comps.length) e.push('components (the source recordings) missing');
    else comps.forEach((c, i) => {
      if (!/^https:\/\//.test(c.source_url || '')) e.push(`component ${i}: source_url missing`);
      if (!/^https:\/\//.test(c.download_url || '')) e.push(`component ${i}: download_url missing`);
      if (!/^(CC0 1\.0|Public Domain Dedication)/.test(c.licence || '')) e.push(`component ${i}: licence "${c.licence}" not CC0/PD`);
      if (!c.author) e.push(`component ${i}: author missing`);
      if (!/^[0-9a-f]{64}$/.test(c.sha256 || '')) e.push(`component ${i}: sha256 of the downloaded source missing`);
    });
  } else if (!j.model || !j.model_licence) e.push('original tracks need model + model_licence');
  if (!/^[0-9a-f]{64}$/.test(j.sha256 || '')) e.push('sha256 of the library file missing');
  else if (audio && fs.existsSync(audio) && sha256(audio) !== j.sha256) e.push('sha256 does not match the audio file');
  if (audio && !fs.existsSync(audio)) e.push(`audio file ${path.basename(audio)} missing`);
  return e;
}

// Every audio file needs a valid licence JSON and every licence JSON its audio file.
export function checkLibrary(dir = LIBRARY) {
  const errors = [];
  const files = fs.existsSync(dir) ? fs.readdirSync(dir) : [];
  const audio = files.filter((f) => /\.(ogg|opus|mp3|wav|flac|m4a|aac)$/i.test(f));
  for (const f of audio) {
    const lic = path.join(dir, f.replace(/\.[^.]+$/, '.licence.json'));
    if (!fs.existsSync(lic)) { errors.push(`${f}: no licence JSON`); continue; }
    let j;
    try { j = JSON.parse(fs.readFileSync(lic, 'utf8')); } catch (err) { errors.push(`${f}: licence JSON unreadable (${err.message})`); continue; }
    for (const p of validateLicence(j, path.join(dir, f))) errors.push(`${f}: ${p}`);
    if (j.id && j.id !== f.replace(/\.[^.]+$/, '')) errors.push(`${f}: id "${j.id}" does not match the file name`);
  }
  for (const f of files.filter((x) => x.endsWith('.licence.json'))) {
    const stem = f.slice(0, -'.licence.json'.length);
    if (!audio.some((a) => a.replace(/\.[^.]+$/, '') === stem)) errors.push(`${f}: no audio file`);
  }
  return { ok: !errors.length && audio.length > 0, tracks: audio.length, errors: audio.length ? errors : ['library is empty', ...errors] };
}

// Valid tracks only (an invalid one is never used, even if the build check was skipped).
export function loadLibrary(dir = LIBRARY) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => f.endsWith('.licence.json')).flatMap((f) => {
    const j = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    const audio = fs.readdirSync(dir).find((a) => a.replace(/\.[^.]+$/, '') === f.slice(0, -13) && !a.endsWith('.json'));
    if (!audio || validateLicence(j, path.join(dir, audio)).length) return [];
    return [{ ...j, file: path.join(dir, audio) }];
  });
}

export function moodFor(spec) {
  if (MOODS.includes(spec.music_mood)) return spec.music_mood;
  const slug = `${spec.slug || ''}`.toLowerCase();
  const text = `${slug} ${spec.title || ''} ${spec.youtube_title || ''} ${spec.kicker || ''}`.toLowerCase();
  if (spec.format === 'status' || spec.festival || /-status-|festival|tyohar|utsav|janmotsav|diwali|holi|navratri/.test(text)) return 'festive';
  if (/katha|kahani|story|movie|itihas/.test(text) || spec.format === 'long') return 'emotional';
  if (/aarti|arti|sandhya|bhajan|kirtan/.test(text)) return 'aarti';
  if (/darshan|evening|mandir|temple|shringar/.test(text)) return 'calm';
  return 'calm';
}

// Track ids used per date, from the published specs (story/published/<YYYY-MM-DD>-...json with spec.music.id).
export function historyFrom(publishedDir) {
  if (!fs.existsSync(publishedDir)) return [];
  return fs.readdirSync(publishedDir).filter((f) => /^\d{4}-\d{2}-\d{2}-.*\.json$/.test(f) && !f.endsWith('.meta.json')).flatMap((f) => {
    try {
      const j = JSON.parse(fs.readFileSync(path.join(publishedDir, f), 'utf8'));
      return j.music?.id ? [{ date: f.slice(0, 10), id: j.music.id, slug: j.slug }] : [];
    } catch { return []; }
  });
}

const dayNo = (iso) => Math.floor(Date.parse(`${iso}T00:00:00Z`) / 864e5);
const hash = (s) => [...`${s}`].reduce((h, c) => (Math.imul(h, 31) + c.charCodeAt(0)) >>> 0, 7);

// Pick one track: mood first (then neighbouring moods), never one used in the 7 days before `date` (or the same day);
// if every candidate was used, the least recently used one. Stable for the same slug and history.
export function pickTrack(tracks, { mood, date, slug, history = [] }) {
  if (!tracks.length) return null;
  const today = dayNo(date);
  const lastUse = new Map();
  for (const h of history) {
    if (h.slug && h.slug === slug) continue; // a re-render of the same video keeps its own pick
    const d = dayNo(h.date);
    if (d <= today && (!lastUse.has(h.id) || d > lastUse.get(h.id))) lastUse.set(h.id, d);
  }
  const fresh = (t) => !lastUse.has(t.id) || today - lastUse.get(t.id) >= REPEAT_DAYS;
  for (const m of [mood, ...(NEIGHBOURS[mood] || [])]) {
    const pool = tracks.filter((t) => t.moods.includes(m) && fresh(t)).sort((a, b) => a.id.localeCompare(b.id));
    if (pool.length) return { track: pool[hash(slug || date) % pool.length], mood: m, reused: false };
  }
  const lru = [...tracks].sort((a, b) => (lastUse.get(a.id) ?? -1e9) - (lastUse.get(b.id) ?? -1e9) || a.id.localeCompare(b.id));
  const inMood = lru.filter((t) => t.moods.includes(mood));
  return { track: (inMood[0] || lru[0]), mood, reused: true };
}

// For story/render-story.mjs: null when the engine is off or has no valid track (the old synthesized drone is used).
// The library is normalised to -16 LUFS. Bed gain per mood (local A/B, 11 Nov 2026): in the pauses the music sits ~8-10 dB
// under the voice (-14 LUFS master), and the existing sidechain ducks it further while a line is spoken.
const GAIN_DB = { festive: -2, aarti: -4, calm: -5, emotional: -5 };
export function musicFor(spec, { date, publishedDir, library = LIBRARY, env = process.env } = {}) {
  if (env.MUSIC_ENGINE !== 'on') return null;
  // Instrumental beds only: the sung bhajans (kind "vocal", music/bhajan.mjs) never go under a narration.
  const tracks = loadLibrary(library).filter((t) => t.kind !== 'vocal');
  const day = date || spec.date || `${spec.slug || ''}`.slice(0, 10) || new Date().toISOString().slice(0, 10);
  const pick = pickTrack(tracks, { mood: moodFor(spec), date: day, slug: spec.slug, history: historyFrom(publishedDir || path.join(DIR, '..', 'story', 'published')) });
  if (!pick) return null;
  const t = pick.track;
  const db = Number(env.MUSIC_GAIN_DB ?? GAIN_DB[pick.mood] ?? -5);
  return {
    input: ['-stream_loop', '-1', '-i', t.file],
    filter: `aresample=48000,aformat=sample_rates=48000:channel_layouts=stereo,volume=${db}dB,afade=t=in:d=0.6`,
    meta: { id: t.id, mood: pick.mood, title: t.title || t.id, licence: t.licence, licence_url: t.licence_url, attribution: t.attribution ?? null, reused: pick.reused },
  };
}

// ffmpeg two-pass loudness normalisation to -16 LUFS / -1.5 dBTP, Opus 96 kb/s stereo 48 kHz (the library format).
export function normaliseLoudness(src, dst, { start = 0, dur = 0, fadeIn = 0.5, fadeOut = 2, pre = '' } = {}) {
  const cut = [...(start ? ['-ss', String(start)] : []), '-i', src, ...(dur ? ['-t', String(dur)] : [])];
  const chain = [pre, 'aresample=48000', 'aformat=channel_layouts=stereo'].filter(Boolean).join(',');
  const probe = spawnSync('ffmpeg', ['-hide_banner', '-nostats', ...cut, '-af', `${chain},loudnorm=I=-16:TP=-1.5:LRA=11:print_format=json`, '-f', 'null', '-'], { encoding: 'utf8' });
  const m = (probe.stderr || '').match(/\{[^{}]*"input_i"[^{}]*\}/s);
  if (!m) throw new Error(`loudness probe failed for ${src}`);
  const j = JSON.parse(m[0]);
  const len = dur || Number((spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', src], { encoding: 'utf8' }).stdout || '0').trim()) - start;
  const fades = `${fadeIn ? `afade=t=in:d=${fadeIn},` : ''}${fadeOut && len > fadeOut ? `afade=t=out:st=${(len - fadeOut).toFixed(2)}:d=${fadeOut},` : ''}`;
  const af = `${chain},${fades}loudnorm=I=-16:TP=-1.5:LRA=11:measured_I=${j.input_i}:measured_TP=${j.input_tp}:measured_LRA=${j.input_lra}:measured_thresh=${j.input_thresh}:offset=${j.target_offset}:linear=true,aresample=48000`;
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  const r = spawnSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...cut, '-af', af, '-c:a', 'libopus', '-b:a', '96k', '-ar', '48000', '-ac', '2', dst], { encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`encode failed for ${src}: ${r.stderr}`);
  return dst;
}
