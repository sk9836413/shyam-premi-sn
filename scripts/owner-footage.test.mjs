// scripts/owner-footage.mjs + its upload-guard / fb.mjs / ai-disclosure rules. Run: node --test scripts/owner-footage.test.mjs
import { describe, test } from 'node:test';
import assert from 'node:assert/strict';
import { SEND_LINE, assetName, buildSpec, checkSpec, loadPlan, nextClip, publishedClips, skipped } from './owner-footage.mjs';
import { aiDisclosure } from './ai-disclosure.mjs';
import { fbVideoCaption } from './fb.mjs';
import { syntheticMedia } from './youtube.mjs';
import { decide, kindOf } from './upload-guard.mjs';

const plan = loadPlan();
const ORDER = ['01', '08', '10', '03', '02', '05', '06', '07', '09', '04'];
const NOW = Date.parse('2026-11-20T16:40:00Z'); // 22:10 IST
const human = { id: 'cc-x', title: 'Temple bells', licence: 'original arrangement of CC0 / public-domain-dedicated recordings (Shyam Premi SN, music/build-library.mjs)', kind: 'instrumental' };
const aiTrack = { id: 'gen-i-x', title: 'Aarti groove', licence: 'original, generated by ACE-Step 1.5 (MIT)', kind: 'instrumental' };

describe('plan', () => {
  test('order 01, 08, 10, 03, 02, 05, 06, 07, 09, 04 (04 shows devotees\' faces: last)', () => assert.deepEqual(plan.clips.map((c) => c.id), ORDER));
  test('titles honest, under 100 characters, #Shorts', () => {
    for (const c of plan.clips) {
      assert.ok(c.title.length <= 100, c.title);
      assert.match(c.title, /#Shorts$/);
      assert.doesNotMatch(`${c.title} ${c.line} ${c.roman}`, /\bAI\b|live|aaj ki|today/i);
    }
  });
  test('every clip has a licence-checked instrumental (cc-* human recording) and a valid spec', () => {
    for (const c of plan.clips) {
      assert.match(c.music, /^cc-/);
      const s = buildSpec(plan, c.id, '2026-11-25');
      assert.deepEqual(checkSpec(s), [], c.id);
    }
  });
});

describe('nextClip', () => {
  test('tonight: clip 01 at once (owner: "abhi 1 post kardo")', () => {
    const r = nextClip(plan, { day: '2026-11-20', now: NOW });
    assert.equal(r.go, true);
    assert.equal(r.clip, '01');
    assert.equal(r.publish_at, null);
  });
  test('21 Nov after 01 went out: clip 08 at 09:30', () => {
    const log = '2026-11-20 | owner | 2026-11-20-owner-safed-shringar-darshan | x | y\n';
    const r = nextClip(plan, { day: '2026-11-21', log, now: NOW });
    assert.equal(r.clip, '08');
    assert.equal(r.publish_at, '2026-11-21T09:30');
    assert.equal(r.slug, '2026-11-21-owner-darshan');
  });
  test('one a day: a day with its owner Short gets nothing more', () => {
    const log = '2026-11-21 | owner | 2026-11-21-owner-darshan | x | y\n';
    assert.equal(nextClip(plan, { day: '2026-11-21', log, now: NOW }).go, false);
    const pub = '- 2026-11-21-owner-darshan | youtube: https://youtube.com/shorts/x (public at …)\n';
    assert.equal(nextClip(plan, { day: '2026-11-21', pub, now: NOW }).go, false);
  });
  test('nothing before the start (except the first day), nothing in the past', () => {
    assert.equal(nextClip(plan, { day: '2026-11-19', now: NOW }).go, false);
    assert.equal(nextClip(plan, { day: '2026-11-21', now: Date.parse('2026-11-23T00:00:00Z') }).go, false);
  });
  test('the skip list and missing release assets move to the next clip', () => {
    const log = '2026-11-20 | owner | 2026-11-20-owner-safed-shringar-darshan | x | y\n';
    assert.deepEqual([...skipped('# comment\n08\n10-safed-shringar-close.mp4\n')], ['08', '10']);
    assert.equal(nextClip(plan, { day: '2026-11-21', log, skip: '08\n', now: NOW }).clip, '10');
    const assets = plan.clips.filter((c) => c.id !== '08').map(assetName);
    assert.equal(nextClip(plan, { day: '2026-11-21', log, assets, now: NOW }).clip, '10');
  });
  test('published clips are read from log.md and published.md', () => {
    const pub = '- 2026-11-22-owner-shringar-close-darshan | youtube: https://youtube.com/shorts/y (public at …)\n';
    assert.deepEqual([...publishedClips(plan, { pub }).keys()], ['10']);
  });
});

describe('honest disclosure', () => {
  test('real footage + human CC0 music: no YouTube flag, no Meta label, no AI line anywhere', () => {
    const s = buildSpec(plan, '01', '2026-11-20', { track: human });
    assert.deepEqual(aiDisclosure(s), { youtube: false, meta: false, why: { youtube: [], meta: [] } });
    assert.equal(syntheticMedia(s), false);
    const fb = fbVideoCaption(s).text;
    assert.doesNotMatch(`${fb}\n${s.youtube_description}\n${s.instagram_caption}`, /\bAI\b/);
  });
  test('real footage + AI music: flagged for the music only, never "Chitra AI"', () => {
    const s = buildSpec(plan, '01', '2026-11-20', { track: aiTrack });
    const d = aiDisclosure(s);
    assert.equal(d.youtube, true); // AI music is the whole soundtrack ("Creates music that's the main focus")
    assert.equal(d.meta, true);
    assert.match(s.youtube_description, /Sangeet AI se banaya gaya hai.*Darshan asli hain/);
    const fb = fbVideoCaption(s).text;
    assert.match(fb, /Sangeet AI se banaya gaya hai; darshan asli hain\./);
    assert.doesNotMatch(fb, /Chitra AI/);
  });
  test('forwardable line on YouTube and Instagram; Facebook keeps its no-ask rule', () => {
    const s = buildSpec(plan, '08', '2026-11-21');
    assert.ok(s.youtube_description.includes(SEND_LINE));
    assert.ok(s.instagram_caption.includes(SEND_LINE));
    assert.ok(!fbVideoCaption(s).text.includes('भेजें'));
    assert.match(s.youtube_description, /Shyam Premi SN ne khud .*record kiya/);
  });
});

describe('upload guard: slot owner has its own cap of 1', () => {
  const day = '2026-11-20';
  const log = ['status', 'statusday', 'morning'].map((sl) => `${day} | ${sl} | ${day}-${sl}-x | a | b`).join('\n');
  test('3 Shorts already: the owner Short still goes, and it does not block a planned Short', () => {
    assert.equal(kindOf('owner'), 'owner');
    assert.equal(decide({ log, day, slot: 'owner', slug: `${day}-owner-a`, run: '1.1' }).go, true);
    const withOwner = `${day} | morning | ${day}-morning-x | a | b\n${day} | owner | ${day}-owner-a | a | b\n`;
    assert.equal(decide({ log: withOwner, day, slot: 'evening', slug: `${day}-evening-y`, run: '1.1' }).go, true);
  });
  test('a second owner Short the same day is capped', () => {
    const pub = `- ${day}-owner-a | youtube: https://youtube.com/shorts/x (public now)\n`;
    const d = decide({ pub, day, slot: 'owner', slug: `${day}-owner-b`, run: '1.1' });
    assert.equal(d.go, false);
    assert.equal(d.cap, true);
  });
});
