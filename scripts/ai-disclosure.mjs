// AI / synthetic-content disclosure: the ONE place that decides YouTube's "altered or synthetic content" flag
// (videos.insert status.containsSyntheticMedia) and Meta's AI label (Graph API is_ai_generated on Facebook Reels /
// video stories and Instagram media containers) for every Shyam Premi SN video. scripts/youtube.mjs (syntheticMedia),
// scripts/meta.mjs (Reels, Page videos, Instagram) and scripts/stories.mjs (video stories) all ask aiDisclosure(spec);
// no format sets its own flag any more (owner, 20 Nov 2026: "YouTube and Meta mark the videos as AI, reach suffers").
//
// The rule: label exactly what each platform REQUIRES, never less (a missing required label risks removal and the
// YouTube Partner Program), and stop labelling what the rules say needs no label. Nothing here hides, strips or evades
// a required disclosure, and the descriptions keep their own "Chitra AI ... (sanketik)" / bhajan lines either way.
//
// YouTube (support.google.com/youtube/answer/14328491, read 20 Nov 2026): disclose content that "seems realistic":
// "Makes a real person appear to say or do something they didn't do", "Alters footage of a real event or place",
// "Generates a realistic scene that didn't actually occur", "Creates music that's the main focus of the video"
// (example: "AI generated music"). Not required: unrealistic content ("Someone riding a unicorn through a fantastical
// world", "an AI-generated or altered animation ... in a fully animated video"), production assistance (script,
// thumbnail, title, infographic, captions). Synthetic narration by a voice that imitates no real person is not listed.
// "Disclosing AI content alone won't limit a video's audience or impact its eligibility to earn money."
//
// Meta (about.fb.com/news/2024/02/labeling-ai-generated-images-on-facebook-instagram-and-threads/, updated 1 Apr 2025,
// read 20 Nov 2026): "We'll require people to use this disclosure and label tool when they post organic content with a
// photorealistic video or realistic-sounding audio that was digitally created or altered, and we may apply penalties if
// they fail to do so." Images are exempt; Instagram's help examples include a reel narrated by a realistic AI
// voiceover and a song with AI-generated vocals (label), a cartoon-style AI video (no label).
//
// So, per video:
//   YouTube = AI-sung music anywhere (bhajan, mantra takes, jukebox, loop chorus)
//             OR an AI-generated instrumental that IS the soundtrack (no narration over it)
//             OR realistic AI visuals (hyper-real / realistic style, Kailash "realistic", photo-bank pictures, any
//                style we cannot classify: unsure = label)
//   Meta    = YouTube's reasons OR any AI narration / dialogue voice (realistic-sounding audio) OR any AI-generated
//             instrumental (realistic-sounding audio, also under a voice)
// NOT AI for this purpose: the numpy-synthesized beds (voice/beds.py), the ffmpeg drone/bells, CC0 human recordings
// (music/library cc-*), real temple photos and footage (footage/, real-photos.mjs), and Shyam Baba's real darshan stills
// (footage/shyam-baba-pandal-darshan, scripts/shyam-darshan.mjs: a scene with `real_image` is left out of the look). Stylized looks (3D animated / Pixar,
// cute-3d, 2D illustrated, painting, miniature, clay, hand-drawn) are "not realistic" on YouTube and not photorealistic
// on Meta. Photo posts (images) need no Meta label; the Veo kit Shorts are made by hand in YouTube's own app (YouTube
// labels those itself).

// Looks a format always has when the spec carries no style of its own.
const FORMAT_LOOK = {
  'krishna-pov': '2D illustrated', // characters/krishna-pov/pov.py: 2D illustrated Shri Krishna
  kalyug: 'cute-3d cartoon', // characters/kalyug: the Kalyug ke Bhagwan cartoon cast
};
const REALISTIC = /hyper[- ]?real|photo[- ]?real|\brealistic\b|film still|live[- ]action|\bdslr\b|\bphotograph/i;
const STYLIZED = /3d anim|animated (feature|devotional|movie|film)|pixar|cartoon|cute-3d|illustrat|hand[- ]?drawn|\b2d\b|painting|painterly|miniature|clay art|watercolou?r|anime|storybook/i;
const AI_LICENCE = /generated by|\bAI\b|ace-?step|musicgen|suno|udio/i;
const HUMAN_LICENCE = /^(CC0|Public Domain|original arrangement of CC0)/i;

/** Every non-empty spoken line (`tts` anywhere, intro_tts / outro_tts) = an AI voice speaks in the video. */
export function hasAiVoice(spec = {}) {
  let found = false;
  const walk = (o, key) => {
    if (found || !o) return;
    if (typeof o === 'string') { if (/(^|_)tts$/.test(key) && o.trim()) found = true; return; }
    if (Array.isArray(o)) return o.forEach((x) => walk(x, key));
    if (typeof o === 'object') for (const [k, v] of Object.entries(o)) walk(v, k);
  };
  walk(spec, '');
  // Formats that are always voiced even when a spec comes without its lines (unsure = voiced).
  if (found || spec.kind === 'jukebox') return found; // the jukebox is songs only (and labelled for them anyway)
  return ['long', 'dialogue', 'movie', 'kalyug', 'kailash', 'krishna-pov', 'facts', 'darshan'].includes(spec.format)
    || (!spec.format && Array.isArray(spec.scenes) && spec.scenes.length > 0);
}

/** AI-sung vocals anywhere: a library bhajan (spec.bhajan, also mode "mantra"), a loop chorus, the jukebox, a bhajan Short. */
export function hasAiVocals(spec = {}) {
  return Boolean(spec.bhajan || spec.bhajan_short || spec.bhajan_id || spec.song?.id || spec.audio?.bhajan_id
    || ['mantra', 'jukebox'].includes(spec.kind) || (spec.compile || []).some((c) => c.ai_music));
}

/** An AI-generated instrumental track (music/library "original, generated by ACE-Step"); a library track of unknown licence counts too. */
export function hasAiInstrumental(spec = {}) {
  const lic = [spec.music && typeof spec.music === 'object' ? spec.music : null, spec.audio?.music_id ? spec.audio : null]
    .filter(Boolean).map((m) => String(m.licence || ''));
  return lic.some((l) => AI_LICENCE.test(l) || !HUMAN_LICENCE.test(l));
}

/** 'realistic' | 'stylized' | 'none' (no AI picture at all) for the video's AI visuals. */
export function aiLook(spec = {}) {
  if (spec.format === 'kailash') return spec.style === 'cute-3d' ? 'stylized' : 'realistic'; // kailash-rules styleOf
  if (spec.kind === 'compilation') {
    const arts = (spec.compile || []).map((c) => c.art);
    return arts.length && arts.every((a) => a === 'illustrated') ? 'stylized' : 'realistic';
  }
  const all = Array.isArray(spec.scenes) ? spec.scenes : [];
  // A scene that SHOWED a real picture (render-story / render-long write `real_image`: a licence-checked temple photo or
  // Shyam Baba's real darshan still, scripts/shyam-darshan.mjs) is not an AI visual, whatever its prompt says.
  const shownReal = (s) => Boolean(s?.real_image) || /^footage\//.test(String(s?.image || ''));
  if (all.some(shownReal) && all.every((s) => s?.endcard || shownReal(s))) return 'none';
  const scenes = all.filter((s) => !shownReal(s));
  const images = scenes.map((s) => String(s.image || ''));
  if (images.some((i) => /photo-bank/.test(i))) return 'realistic'; // bank pictures include "realistic photograph" prompts
  const text = [spec.style, spec.picture_style, FORMAT_LOOK[spec.format], ...scenes.map((s) => s.prompt)].filter(Boolean).join(' ');
  if (REALISTIC.test(text)) return 'realistic';
  if (STYLIZED.test(text)) return 'stylized';
  // No AI picture: only real photos / footage (mantra jaap, real-photo scenes) or no scenes at all.
  const aiScenes = scenes.filter((s) => !s.real && !/^footage\//.test(String(s.image || '')));
  if (spec.kind === 'mantra' || (scenes.length && !aiScenes.length)) return 'none';
  return 'realistic'; // a look we cannot classify: unsure = label
}

/**
 * The disclosure for one video spec: { youtube, meta, why: { youtube: [...], meta: [...] } }.
 * youtube -> status.containsSyntheticMedia; meta -> is_ai_generated (Facebook Reels / video stories, Instagram).
 */
export function aiDisclosure(spec) {
  if (!spec || typeof spec !== 'object') spec = {};
  const vocals = hasAiVocals(spec);
  const instrumental = hasAiInstrumental(spec);
  const voice = hasAiVoice(spec);
  const look = aiLook(spec);
  const yt = [];
  if (vocals) yt.push('AI-sung music (YouTube: "Creates music that\'s the main focus of the video")');
  if (instrumental && !voice) yt.push('AI-generated music is the soundtrack (YouTube: "AI generated music")');
  if (look === 'realistic') yt.push('realistic AI visuals (YouTube: "Generates a realistic scene that didn\'t actually occur")');
  const meta = [...yt];
  if (voice) meta.push('AI narration voice (Meta: "realistic-sounding audio that was digitally created")');
  if (instrumental && voice) meta.push('AI-generated background music (Meta: realistic-sounding digitally created audio)');
  return { youtube: yt.length > 0, meta: meta.length > 0, why: { youtube: yt, meta } };
}

/** Graph API parameter: is_ai_generated "true" when Meta requires the label, nothing otherwise (never sends "false"). */
export const metaAiParam = (spec) => (aiDisclosure(spec).meta ? { is_ai_generated: 'true' } : {});
