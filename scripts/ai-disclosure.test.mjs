// scripts/ai-disclosure.mjs: YouTube's altered/synthetic flag and Meta's AI label per format (owner, 20 Nov 2026).
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, test } from 'node:test';
import { aiDisclosure, aiLook, hasAiInstrumental, hasAiVocals, hasAiVoice, metaAiParam } from './ai-disclosure.mjs';
import { metaFromScenes, uploadStatus } from './youtube.mjs';
import { fbVideoAiLabel } from './meta.mjs';
import { storyAiParam } from './stories.mjs';

const PIXAR = '3D animated devotional movie style, Pixar quality, soft cinematic lighting, rich warm colours, no text, no letters, no writing';
const HYPER = 'hyper-real cinematic devotional film still, warm golden sunrise light, deep saturated colours, no text';
const AI_TRACK = { id: 'orig-calm-1', mood: 'calm', licence: 'original, generated by ACE-Step 1.5 (MIT)' };
const CC0_TRACK = { id: 'cc-sitar-room', mood: 'calm', licence: 'CC0 1.0 (excerpt, loudness-normalised)' };
const BHAJAN = { id: 'bhajan-2026w46-12-shiv', licence: 'original, generated by ACE-Step 1.5 (MIT)', singer: 'AI (ACE-Step 1.5), no real singer cloned' };
const scenes = (n = 3, o = {}) => Array.from({ length: n }, (_, i) => ({ prompt: `Mahadev in meditation on Kailash, scene ${i + 1}`, tts: 'हर हर महादेव।', ...o }));
const flags = (s) => { const d = aiDisclosure(s); return [d.youtube, d.meta]; };

describe('per format: [YouTube containsSyntheticMedia, Meta is_ai_generated]', () => {
  test('daily story Short: stylized 3D art + AI narrator = no YouTube flag, Meta label (realistic AI voice)', () => {
    assert.deepEqual(flags({ slug: 'x-morning-shiv', style: PIXAR, scenes: scenes() }), [false, true]);
    assert.deepEqual(flags({ slug: 'x', style: PIXAR, scenes: scenes(), music: CC0_TRACK }), [false, true]);
    // an AI instrumental only as a ducked bed under the narration is not "music that's the main focus"
    assert.deepEqual(flags({ slug: 'x', style: PIXAR, scenes: scenes(), music: AI_TRACK }), [false, true]);
  });
  test('any AI-sung bhajan (outro, long katha intro/outro, status song, bhajan Short) = both labels', () => {
    assert.deepEqual(flags({ style: PIXAR, scenes: scenes(), bhajan: BHAJAN }), [true, true]);
    assert.deepEqual(flags({ format: 'long', style: PIXAR, chapters: [], bhajan: { ...BHAJAN, narration: true } }), [true, true]);
    assert.deepEqual(flags({ format: 'status', bhajan_short: true, style: 'licence-safe AI picture bank (brand/photo-bank), no text, no faces',
      scenes: [{ image: 'brand/photo-bank/chhath/kaggle-flux-2026-11-13-1.jpg', tts: 'जय छठी मइया' }], song: { id: 'b' }, bhajan: BHAJAN }), [true, true]);
  });
  test('festival status: stylized art; CC0 music = no YouTube flag; an AI track as the whole soundtrack = flagged', () => {
    const st = { format: 'status', style: PIXAR, scenes: scenes(2) };
    assert.deepEqual(flags({ ...st, music: CC0_TRACK }), [false, true]);
    assert.deepEqual(flags({ ...st, loop: true, music: CC0_TRACK }), [false, true]);
    const silent = { format: 'status', style: PIXAR, scenes: [{ prompt: 'diyas', line: 'शुभ दीपावली' }] };
    assert.deepEqual(flags({ ...silent, music: CC0_TRACK }), [false, false], 'text + CC0 music, no voice: nothing to label');
    assert.deepEqual(flags({ ...silent, music: AI_TRACK }), [true, true], 'AI music is the soundtrack');
  });
  test('facts Shorts: cinematic (hyper-real) art = both; illustrated art = Meta only', () => {
    assert.deepEqual(flags({ format: 'facts', art: 'cinematic', style: HYPER, scenes: scenes() }), [true, true]);
    assert.deepEqual(flags({ format: 'facts', art: 'illustrated', style: 'warm hand-drawn illustration, clean outlines, soft sunset light', scenes: scenes() }), [false, true]);
  });
  test('loop (AI bhajan chorus) = both; veer with a CC0 bed = none, with an AI bed = both, unknown bed = both', () => {
    const loop = { format: 'loop', kind: 'loop', style: 'rich oil painting style, visible brush strokes, no text', scenes: [{ prompt: 'Mahadev', deity: true }] };
    assert.deepEqual(flags({ ...loop, audio: { bhajan_id: 'bhajan-x', file: 'x.ogg' } }), [true, true]);
    const veer = { format: 'loop', kind: 'veer', style: 'epic painterly digital art, dramatic cinematic lighting, no text', scenes: [{ prompt: 'Mahakal', deity: true }] };
    assert.deepEqual(flags({ ...veer, audio: { music_id: 'cc-dhol-tasha', licence: 'original arrangement of CC0 / public-domain-dedicated recordings' } }), [false, false]);
    assert.deepEqual(flags({ ...veer, audio: { music_id: 'orig-1', licence: AI_TRACK.licence } }), [true, true]);
    assert.deepEqual(flags({ ...veer, audio: { music_id: 'x' } }), [true, true], 'licence unknown: unsure = label');
  });
  test('long katha (3D art + real temple photos + AI narrator): Meta only; with a bhajan: both', () => {
    const long = { format: 'long', style: PIXAR, scenes: scenes(4) };
    assert.deepEqual(flags(long), [false, true]);
    assert.deepEqual(flags({ ...long, bhajan: BHAJAN }), [true, true]);
  });
  test('mantra jaap (AI-sung takes over real temple photos) and the jukebox (AI bhajans) = both', () => {
    assert.deepEqual(flags({ format: 'long', kind: 'mantra', intro: { tts: 'ॐ' }, bhajan: { mode: 'mantra', id: 'm1,m2' } }), [true, true]);
    assert.deepEqual(flags({ format: 'long', kind: 'jukebox', bhajan: BHAJAN }), [true, true]);
    assert.equal(hasAiVoice({ format: 'long', kind: 'jukebox' }), false);
  });
  test('weekly facts compilation follows its Shorts: all illustrated = Meta only, any cinematic or unknown = both', () => {
    const c = (arts, ai_music = false) => ({ format: 'long', kind: 'compilation', intro_tts: 'x', compile: arts.map((art) => ({ art, ai_music })) });
    assert.deepEqual(flags(c(['illustrated', 'illustrated'])), [false, true]);
    assert.deepEqual(flags(c(['illustrated', 'cinematic'])), [true, true]);
    assert.deepEqual(flags(c(['illustrated', null])), [true, true]);
    assert.deepEqual(flags(c(['illustrated'], true)), [true, true]);
  });
  test('character formats: movie / dialogue (stylized 3D), Kalyug (cute-3d), Krishna POV (2D) = Meta only; Kailash realistic = both', () => {
    assert.deepEqual(flags({ format: 'movie', style: 'stylized 3D animated feature film look, Indian mythological epic', music: 'epic', scenes: [{ lines: [{ who: 'narrator', tts: 'x' }] }] }), [false, true]);
    assert.deepEqual(flags({ format: 'dialogue', style: 'stylized 3D animated feature film look', visuals: { temple: { real: true } }, lines: [{ tts: 'x' }] }), [false, true]);
    assert.deepEqual(flags({ format: 'kalyug', music: 'playful', scenes: [{ lines: [{ text: 'x' }] }] }), [false, true]);
    assert.deepEqual(flags({ format: 'krishna-pov', music: 'calm', scenes: [{ lines: [{ text: 'x' }] }] }), [false, true]);
    assert.deepEqual(flags({ format: 'kailash', style: 'cute-3d', music: 'calm', scenes: [] }), [false, true]);
    assert.deepEqual(flags({ format: 'kailash', music: 'calm', scenes: [] }), [true, true], 'Kailash default style is realistic');
    assert.deepEqual(flags({ format: 'kailash', style: 'realistic', scenes: [] }), [true, true]);
  });
  test('unsure = label: an empty or unclassifiable spec is flagged on both', () => {
    assert.deepEqual(flags({}), [true, true]);
    assert.equal(aiDisclosure(null).youtube, true);
    assert.equal(aiLook({ scenes: [{ prompt: 'a temple at dawn' }] }), 'realistic');
    assert.equal(aiLook({ style: 'realistic photograph of a diya', scenes: [{ prompt: 'x' }] }), 'realistic');
    assert.equal(aiLook({ style: PIXAR, scenes: [{ prompt: 'a realistic photograph of a diya' }] }), 'realistic', 'a realistic scene prompt wins');
    assert.equal(aiLook({ scenes: [{ image: 'footage/khatu/1.jpg', real: true }] }), 'none');
  });
  test('signals', () => {
    assert.equal(hasAiVocals({ audio: { bhajan_id: 'b' } }), true);
    assert.equal(hasAiVocals({ music: AI_TRACK }), false);
    assert.equal(hasAiInstrumental({ music: AI_TRACK }), true);
    assert.equal(hasAiInstrumental({ music: CC0_TRACK }), false);
    assert.equal(hasAiInstrumental({ music: 'epic' }), false, 'movie.py synthesizes its bed');
    assert.equal(hasAiVoice({ format: 'status', scenes: [{ line: 'x' }] }), false);
    assert.equal(hasAiVoice({ outro_tts: 'जय' }), true);
  });
});

describe('the uploaders use it', () => {
  test('YouTube: metaFromScenes -> uploadStatus.containsSyntheticMedia follows the rule (a missing decision = declared)', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ai-yt-'));
    const f = path.join(dir, 's.json');
    const base = { youtube_title: 'Somvar Vishesh #Shorts', youtube_description: 'x', youtube_tags: 'a,b', style: PIXAR, scenes: scenes() };
    fs.writeFileSync(f, JSON.stringify(base));
    assert.equal(uploadStatus(metaFromScenes(f), {}).containsSyntheticMedia, false);
    fs.writeFileSync(f, JSON.stringify({ ...base, bhajan: BHAJAN }));
    assert.equal(uploadStatus(metaFromScenes(f), {}).containsSyntheticMedia, true);
    assert.equal(uploadStatus({}, {}).containsSyntheticMedia, true);
    fs.rmSync(dir, { recursive: true, force: true });
  });
  test('Meta: is_ai_generated "true" or nothing (never sends false); video stories follow the source Short', () => {
    assert.deepEqual(metaAiParam({ style: PIXAR, scenes: scenes() }), { is_ai_generated: 'true' });
    assert.deepEqual(metaAiParam({ format: 'status', style: PIXAR, scenes: [{ line: 'x' }], music: CC0_TRACK }), {});
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ai-st-'));
    fs.mkdirSync(path.join(root, 'story', 'published'), { recursive: true });
    fs.writeFileSync(path.join(root, 'story', 'published', 'a.json'), JSON.stringify({ format: 'status', style: PIXAR, scenes: [{ line: 'x' }], music: CC0_TRACK }));
    assert.deepEqual(storyAiParam('a', root), {});
    assert.deepEqual(storyAiParam('missing', root), { is_ai_generated: 'true' }, 'no spec: labelled');
    fs.rmSync(root, { recursive: true, force: true });
  });
  test('Facebook Page videos: the label is asked for after the upload and a refusal never fails the post', async () => {
    const calls = [];
    assert.deepEqual(await fbVideoAiLabel('123', { is_ai_generated: 'true' }, { post: async (...a) => { calls.push(a); return { success: true }; } }), { aiLabel: true });
    assert.deepEqual(calls, [['POST', '123', { is_ai_generated: 'true' }]]);
    const no = await fbVideoAiLabel('123', { is_ai_generated: 'true' }, { post: async () => { throw new Error('(#100) Unknown parameter'); } });
    assert.match(no.aiLabel, /Meta Business Suite/);
    assert.deepEqual(await fbVideoAiLabel('123', {}, { post: async () => { throw new Error('must not be called'); } }), { aiLabel: false });
  });
});
